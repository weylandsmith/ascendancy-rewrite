#!/usr/bin/env python3
"""gam_probe.py — P1d: correlate game/resume.gam with the plaintext tables.

resume.gam (81,647 B, entropy ~2.65, ~60% NUL) is a sparse u32-LE savegame.
This probe does NOT claim a full layout — field meanings need the exe's
save/load code, so OQ-003 stays open. What it establishes, measured:

 * `restree.txt` lists 107 tech rows; the save stores tech names in a
   fixed-stride record whose stride is MEASURED from consecutive-name
   offsets (never assumed).
 * The numeric fields for tech 0 (`0 50 255`) appear as bytes 50 and 255 at
   fixed record offsets — a positional match on ONE record, therefore marked
   [inferred], not [verified].

Output docs/re/savegame.md is generated deterministically; gate stage 3f
asserts the summary line so a silently-changed golden save or a broken
stride invariant fails the build.

Usage: gam_probe.py [--out FILE] [--quiet]
NOTE: --out DEFAULTS to docs/re/savegame.md, which carries hand-written
sections BELOW the generated block (golden-tour notes 2026-10-05e). A bare
run truncates them. Regenerating the doc must be followed by git review, or
pass --out /tmp/... (what gate stage 3f does). [pitfall hit 2026-10-05k]
"""
import argparse, os, re, re as RE, struct, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAM = os.path.join(ROOT, 'game', 'resume.gam')
RESTREE = os.path.join(ROOT, 'extracted', 'ascend00', 'restree.txt')
NUL = b'\x00'


def parse_restree(path):
    rows = []
    for ln in open(path, 'rb').read().decode('cp437').split('\r\n'):
        ln = ln.strip()
        if not ln or ln.startswith('//') or ln.startswith('#'):
            continue
        toks = ln.split()
        if not toks or toks[0].isdigit():
            continue
        name = toks[0].replace('^', ' ')
        nums = [int(t) for t in toks[1:] if t.lstrip('-').isdigit()]
        rows.append((name, nums))
    return rows


def longest_chain(offsets, stride):
    """Longest run of offsets spaced exactly `stride` apart."""
    s = sorted(set(offsets))
    best = [s[0]]
    cur = [s[0]]
    for o in s[1:]:
        if o == cur[-1] + stride:
            cur.append(o)
        else:
            if len(cur) > len(best):
                best = cur
            cur = [o]
    return best if len(cur) <= len(best) else cur


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 're', 'savegame.md'))
    ap.add_argument('--quiet', action='store_true')
    args = ap.parse_args()

    d = open(GAM, 'rb').read()
    N = len(d)
    if N != 81647:
        print(f"[gam_probe] FAIL: resume.gam is {N} B, expected 81647 — the golden save "
              f"changed; re-verify before trusting any numbers here", file=sys.stderr)
        return 1

    rows = parse_restree(RESTREE)
    offsets = [d.find(name.encode('cp437')) for name, _ in rows]
    found = sum(1 for o in offsets if o >= 0)

    # New 2026-10-05 (OQ-003/OQ-013 evidence, pinned here so it can't rot):
    #  (a) NO version stamp: the file starts with plain LE ints, no magic.
    #  (b) NO exact-ALL-CAPS variant name appears ANYWHERE in the save:
    #      display names are title-case only, so the shipped golden save
    #      shows main-tree display strings (variant identity cannot be
    #      separated by casing from save data alone).
    if d[:8] != bytes.fromhex('0000000007000000'):
        print('[gam_probe] FAIL: header bytes changed — version-stamp finding '
              'needs re-verification', file=sys.stderr)
        return 1
    caps_rows = [(name, nums) for name, nums in rows if name.isupper()]
    caps_exact = sum(1 for name, _ in caps_rows
                     if d.find(name.encode('cp437')) >= 0)
    if caps_exact != 0:
        print(f'[gam_probe] FAIL: {caps_exact} ALL-CAPS variant names now in '
              f'save — title-case-only finding broken', file=sys.stderr)
        return 1

    dd = collections.Counter(offsets[i + 1] - offsets[i]
                             for i in range(len(offsets) - 1)
                             if offsets[i] >= 0 and offsets[i + 1] >= 0)
    stride, pairs_at_stride = dd.most_common(1)[0]
    chain = longest_chain([o for o in offsets if o >= 0], stride)
    lo, hi = chain[0], chain[-1] + stride
    by_off = {o: row for row, o in zip(rows, offsets) if o >= 0}

    out = []
    P = out.append
    P("# P1d — resume.gam (correlation with restree.txt; partial)")
    P("")
    P("Generated by `scripts/gam_probe.py`. This is a **correlation** document, not a")
    P("layout spec — field meanings require the exe save/load subsystem, so OQ-003 stays")
    P("open. Gate stage 3f re-runs this script and pins the golden save's size.")
    P("")
    P("## Measured properties [verified]")
    P("")
    P(f"- size {N} B; NUL fraction {d.count(0)/N:.3f}; head u32s "
      f"{[struct.unpack_from('<I', d, i)[0] for i in range(0, 16, 4)]}")
    P("- **no version stamp** (OQ-003 half-answered): the header is plain "
      f"LE ints starting `{d[:8].hex()}` — no magic word anywhere in the file.")
    P("- **no ALL-CAPS variant name appears in the save** (0/40 exact): "
      "display names are title-case only, so a save can never show which "
      "variant-block row it came from by casing alone (feeds OQ-013).")
    P(f"- `restree.txt` yields {len(rows)} tech rows (name + numeric fields)")
    P(f"- {found}/{len(rows)} row names appear verbatim (CP437) in the save")
    P(f"- consecutive-name delta histogram is dominated by one value: **{stride}** "
      f"({pairs_at_stride} pairs); runner-ups: {dd.most_common(5)[1:4]}")
    P(f"- longest exact stride-{stride} chain: **{len(chain)} records**, "
      f"{lo:#06x}..{hi:#06x} ({hi-lo} B, = {len(chain)}x{stride})")
    P("")
    P("## Records in the chain (offsets verified, meanings UNVERIFIED)")
    P("")
    P("| off | name in save | restree fields | bytes +56.. |")
    P("|---|---|---|---|")
    for k, o in enumerate(chain):
        if k >= 8 and k < len(chain) - 3 and k % 20:
            continue
        if k == 8:
            P(f"| … | ({len(chain)-11} more records) | | |")
        name_save = d[o:o + stride].split(NUL)[0].decode('cp437', 'replace')
        fields = by_off.get(o, ('', []))[1]
        P(f"| {o:#06x} | {name_save} | {fields} | {d[o+56:o+stride].hex()} |")
    P("")
    P("Positional cross-check on the first record only: restree gives tech 0 the fields")
    P(f"`{by_off.get(chain[0], ('',[]))[1]}`; the save has byte {d[lo+60]} at record +60 and")
    P(f"{d[lo+62]} at +62 with zeros in the rest of +56..{stride-1}. Two values matching at")
    P("fixed positions is suggestive but is a sample of n=1, so the mapping is")
    P("**[inferred]**; closing OQ-003 requires checking it across the whole tree.")
    P("")
    P("## restree rows absent from the save")
    P("")
    miss = [name for (name, _), o in zip(rows, offsets) if o < 0]
    upper = sum(1 for m in miss if m.isupper())
    P(f"{len(miss)} rows, of which {upper} are ALL-CAPS. So the missing set is the")
    P("category/label rows of restree rather than actual techs — the save keys techs by")
    P("display name and the caps rows are grouping headings in the text file.")
    P("")
    for m in miss[:12]:
        P(f"- {m}")
    P(f"- … ({len(miss)} total; generated list, not hand-copied)")
    P("")
    P("## Status")
    P("")
    P("- [x] stride {} measured from {} consecutive pairs".format(stride, pairs_at_stride))
    P("- [x] {}-record chain located and byte-dumped".format(len(chain)))
    P("- [x] version stamp: NONE exists (header bytes pinned above) — OQ-003")
    P("      closed on that half; the field meanings + packed regions below")
    P("      remain unmapped and need the exe save/load subsystem (R1).")
    P("")

    text = "\n".join(out) + "\n"
    if args.out:
        open(args.out, 'w').write(text)
    if not args.quiet:
        print(text)
    print(f"[gam_probe] OK: stride={stride} chain={len(chain)} found={found}/{len(rows)}",
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
