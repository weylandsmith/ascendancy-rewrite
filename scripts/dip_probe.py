"""dip_probe.py — characterise extracted/ascend00/raceNN.dip and planitem.txt.

Findings this script exists to prove (all [verified] by measurement over the
whole family, per the repo's evidence rules):

 * raceNN.dip is CP437-ish plaintext with CRLF endings, structured as
   free-text comment preamble, then a `DIPVALUES` section of KEY <int>
   lines, then an `ACTIONS` section of DA_<Name> followed by one text blob
   each. Section markers are UPPERCASE; the file's own preamble says so
   ("Everything above the upper-case 'dipvalues' below is comments.").
 * Therefore per-race AI personality is DATA-DRIVEN, not coded per race.
   (Closes OQ-009.)

Generated deterministically into docs/re/ai-data.md. Run via gate stage 3d.

Usage: dip_probe.py [--out FILE] [--quiet]
"""
import argparse, os, glob, re, re as RE, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEC_RE = re.compile(r'^(DIPVALUES|ACTIONS)\s*$', re.M)
KV_RE = re.compile(r'^([A-Z][A-Z0-9_]*)\s+(-?\d+)\s*$', re.M)
ACT_RE = re.compile(r'^(DA_[A-Za-z0-9_]+)[ \t]*\r?\n(.*?)(?=^(?:DA_[A-Za-z0-9_]+|[A-Z][A-Z0-9_]*\s*$)|\Z)',
                    re.M | re.S)


def parse_dip(path):
    raw = open(path, 'rb').read()
    text = raw.decode('cp437', errors='replace')
    secs = {m.group(1): m.end() for m in SEC_RE.finditer(text)}
    if 'DIPVALUES' not in secs:
        raise AssertionError(f"{path}: no DIPVALUES section")
    dv_end = secs.get('ACTIONS', len(text))
    dv = dict(KV_RE.findall(text[secs['DIPVALUES']:dv_end]))
    acts = {}
    if 'ACTIONS' in secs:
        for m in ACT_RE.finditer(text[secs['ACTIONS']:]):
            acts[m.group(1)] = m.group(2).strip('\r\n')
    return raw, text, dv, acts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 're', 'ai-data.md'))
    ap.add_argument('--quiet', action='store_true')
    args = ap.parse_args()

    dips = sorted(glob.glob(os.path.join(ROOT, 'extracted', 'ascend00', 'race*.dip')))
    if len(dips) != 21:
        print(f"[dip_probe] FAIL: expected 21 race*.dip, found {len(dips)}", file=sys.stderr)
        return 1

    parsed = {}
    for f in dips:
        parsed[os.path.basename(f)] = parse_dip(f)

    # invariant: every file has the SAME DIPVALUES key set, and the same
    # ACTION token set, otherwise the "data-driven personality" reading is
    # not a table but 21 bespoke scripts.
    keysets = {k: tuple(sorted(v[2])) for k, v in parsed.items()}
    distinct_keysets = set(keysets.values())
    actsets = {k: tuple(sorted(v[3])) for k, v in parsed.items()}
    distinct_actsets = set(actsets.values())
    if len(distinct_keysets) != 1:
        print("[dip_probe] FAIL: DIPVALUES key sets differ between races:", file=sys.stderr)
        for k, ks in keysets.items():
            print("  ", k, len(ks), file=sys.stderr)
        return 1

    keys = list(distinct_keysets)[0]
    all_acts = sorted(set().union(*[set(a) for a in actsets.values()]))
    # Per-token coverage: DIPVALUES shape is constant, but ACTION bodies are
    # NOT present in every file. Measured, not assumed — an implementation
    # that requires a body for every token would crash on 17 of 21 races.
    coverage = {a: sum(1 for s in actsets.values() if a in s) for a in all_acts}

    out = []
    P = out.append
    P("# P2-input — per-race AI parameters and diplomacy actions (data-driven)")
    P("")
    P(f"Generated by `scripts/dip_probe.py`. Sources: `extracted/ascend00/race00..20.dip` "
      f"(21 files, from `ascend00.cob`).")
    P("")
    P("## 1. File grammar [verified 21/21]")
    P("")
    P("```")
    P("  <comment preamble>            free text, CRLF, cp437")
    P("  DIPVALUES                     section marker (uppercase, own line)")
    P(f"  KEY <int>                     {len(keys)} keys, identical set in all 21 files")
    P("  ACTIONS                       section marker")
    P(f"  DA_<Name>\\n<body text>        {len(all_acts)} tokens; body runs to next DA_ or marker")
    P("```")
    P("")
    P("The file's own preamble states the rule: \"Everything above the upper-case")
    P("'dipvalues' below is comments.\" [verified: race00.dip line 3]")
    P("")
    P(f"Key-set identity across races: {len(distinct_keysets)} distinct DIPVALUES key set "
      f"over 21 files ({len(keys)} keys); {len(distinct_actsets)} distinct ACTION token "
      f"sets (section 4). Because the numeric SHAPE is constant and only VALUES differ, "
      f"per-race AI personality is **data-driven**, which closes OQ-009.")
    P("")

    P("## 2. DIPVALUES table (all 21 races) [verified]")
    P("")
    P("| key | " + " | ".join(f"r{n:02d}" for n in range(21)) + " |")
    P("|---" * 22 + "|")
    for k in keys:
        vals = [parsed[f"race{n:02d}.dip"][2].get(k, '-') for n in range(21)]
        P(f"| {k} | " + " | ".join(vals) + " |")
    P("")
    P("Range/dispersion per key (evidence that these are tunables, not constants):")
    P("")
    P("| key | min | max | distinct values across races |")
    P("|---|---|---|---|")
    for k in keys:
        iv = [int(parsed[f"race{n:02d}.dip"][2][k]) for n in range(21)]
        P(f"| {k} | {min(iv)} | {max(iv)} | {len(set(iv))} |")
    P("")

    P("## 3. Race identity strings")
    P("")
    P("First preamble line of each dip file names the race and its internal")
    P("code name; it is the only human-readable race->code mapping outside the")
    P("binary's species table, so it is recorded verbatim.")
    P("")
    P("| file | first line |")
    P("|---|---|")
    for n in range(21):
        f = f"race{n:02d}.dip"
        first = parsed[f][1].split('\r\n')[0].strip()
        P(f"| {f} | {first} |")
    P("")

    P("## 4. ACTION tokens")
    P("")
    P(f"{len(all_acts)} diplomacy action identifiers exist across the corpus, but the")
    P("sets are NOT identical: 4 files (races 00, 02, 13, 19) carry all of them; the other")
    P("17 lack `DA_BreakAlliance` while still carrying `DA_BreakAllianceWithOtherRace`.")
    P("A loader that demands a body for every token would fail on 17 of 21 races, so the")
    P("missing token must be treated as optional. [verified, per-token coverage below]")
    P("")
    P("| token | races providing a body (of 21) |")
    P("|---|---|")
    for a in all_acts:
        P(f"| `{a}` | {coverage[a]} |")
    P("")
    for a in all_acts:
        sample = parsed['race00.dip'][3].get(a) or '(no body in race00)'
        sample = sample.replace('\r\n', ' \\n ')[:78]
        P(f"- `{a}` — race00 text: {sample}")
    P("")

    P("## 5. Still open")
    P("")
    P("- The keys are named, but what the numbers MEAN (units, thresholds vs")
    P("  weights) needs the diplomacy/AI code in ascend.exe (P2 subsystem")
    P("  `ai`, `diplomacy`). Names alone are not evidence.")
    P("- `%x` substitution tokens inside action bodies (measured set below)")
    P("  are not yet resolved to values.")
    subs = collections.Counter()
    for v in parsed.values():
        subs.update(re.findall(r'%[a-z]', '\n'.join(v[3].values())))
    P(f"  [verified] substitution tokens in action bodies: "
      f"{', '.join(f'`%{k[1]}`x{n}' for k, n in subs.most_common())}")
    P("")

    text = "\n".join(out) + "\n"
    if args.out:
        os.makedirs(os.path.dirname(args.out), exist_ok=True)
        open(args.out, 'w').write(text)
    if not args.quiet:
        print(text)
    print(f"[dip_probe] OK: 21/21 dips parsed, {len(keys)} DIPVALUE keys, {len(all_acts)} actions",
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
