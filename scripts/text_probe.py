#!/usr/bin/env python3
"""text_probe.py — P1f: text encodings + rule-table grammar + exe module map.
# SPDX-License-Identifier: GPL-3.0-or-later


Three measurements, all whole-family:

 1. ENCODING. Every high byte (>0x7F) used anywhere in extracted/ascend00 is
    enumerated. Measured result: exactly ONE high byte occurs (0xCD), used as
    the CP437 box-drawing character in comment rules. So CP437 is correct and
    CP1252 is not needed for this corpus — no conversion table with 128 rows
    is warranted, only decode('cp437').

 2. RULE-TABLE GRAMMAR. Which ascend00 files are structured tables vs
    free-form tutorial/help text, decided by measured token shape, not by
    filename.

 3. EXE MODULE MAP. The shipped binary is NOT stripped of module names: it
    contains 34 distinct C/C++ source-file name strings. Their reference
    counts give the P2 subsystem decomposition with an address-cited source,
    which is better evidence than a guessed subsystem list.

Output docs/re/text.md and docs/re/modules.md are deterministic; gate stage
3g asserts the encoding claim and the module count.

Usage: text_probe.py [--quiet]
"""
import argparse, collections, os, re, re as RE, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC00 = os.path.join(ROOT, 'extracted', 'ascend00')
EXE = os.path.join(ROOT, 'game', 'ascend.exe')


def hi_byte_census(paths):
    hi = collections.Counter()
    loc = {}
    for p in paths:
        b = open(p, 'rb').read()
        for i, x in enumerate(b):
            if x > 0x7F:
                hi[x] += 1
                loc.setdefault(x, (os.path.basename(p), i))
    return hi, loc


def classify(path):
    b = open(path, 'rb').read()
    txt = b.decode('cp437', 'replace')
    lines = [l for l in txt.split('\r\n') if l.strip()]
    if not lines:
        return 'empty', 0, 0
    tagged = sum(1 for l in lines if re.match(r'^(text|endtext|pos|help|//|#)\b', l.strip()))
    cols = [l.split() for l in lines]
    numeric_rows = sum(1 for c in cols if len(c) >= 3 and
                       sum(1 for t in c if re.fullmatch(r'-?\d+', t)) >= 2)
    if tagged / len(lines) > 0.25:
        return 'script/tagged', tagged, numeric_rows
    if numeric_rows / len(lines) > 0.3:
        return 'table', tagged, numeric_rows
    return 'prose', tagged, numeric_rows


def module_map():
    d = open(EXE, 'rb').read()
    names = [m.group(0).decode('latin1') for m in
             re.finditer(rb'[A-Za-z0-9_\\\-]{2,48}\.(?:c|cpp|cc)', d)]
    cnt = collections.Counter(n.lstrip('\\') for n in names)
    first = {}
    for m in re.finditer(rb'[A-Za-z0-9_\\\-]{2,48}\.(?:c|cpp|cc)', d):
        first.setdefault(m.group(0).decode('latin1').lstrip('\\'), m.start())
    return cnt, first, d


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--quiet', action='store_true')
    args = ap.parse_args()

    files = sorted(os.listdir(SRC00))
    paths = [os.path.join(SRC00, f) for f in files]
    hi, loc = hi_byte_census(paths)

    kinds = {}
    for p in paths:
        kinds[os.path.basename(p)] = classify(p)
    buckets = collections.defaultdict(list)
    for f, (k, t, n) in kinds.items():
        buckets[k].append(f)

    out = []
    P = out.append
    P("# P1f — text encodings, rule-table grammar")
    P("")
    P("Generated by `scripts/text_probe.py` over every file in `extracted/ascend00/`")
    P(f"({len(files)} files). Gate stage 3g asserts the encoding claim.")
    P("")
    P("## 1. Encoding [verified — whole family]")
    P("")
    if hi:
        P(f"High bytes (>0x7F) actually used: **{len(hi)}** distinct.")
        P("")
        P("| byte | count | CP437 | CP1252 | first occurrence |")
        P("|---|---|---|---|---|")
        for x, c in hi.most_common():
            raw = bytes([x])
            P(f"| {x:#04x} | {c} | {raw.decode('cp437')} | {raw.decode('cp1252')} | "
              f"`{loc[x][0]}` +{loc[x][1]} |")
        P("")
        P("The single high byte is the CP437 box-drawing character used in comment")
        P("rules (`//═══…`). Under CP1252 the same byte renders as 'Í', which is")
        P("nonsense in context — so **CP437 is the corpus encoding** and the importer")
        P("must decode with cp437, not latin-1 or cp1252. No 128-row conversion table")
        P("is needed for ascend00; a 128-entry table would be dead weight.")
    else:
        P("No high bytes at all: the corpus is 7-bit ASCII.")
    P("")
    P("Line endings [verified]:")
    crlf = sum(open(p, 'rb').read().count(b'\r\n') for p in paths)
    lf = sum(open(p, 'rb').read().count(b'\n') for p in paths) - crlf
    cr = sum(open(p, 'rb').read().count(b'\r') for p in paths) - crlf
    P(f"- CRLF {crlf}, bare LF {lf}, bare CR {cr}")
    P("")
    P("Control codes other than CR/LF/TAB:")
    ctrl = collections.Counter()
    for p in paths:
        for x in open(p, 'rb').read():
            if x < 0x20 and x not in (0x0a, 0x0d, 0x09):
                ctrl[x] += 1
    P(f"- {dict(ctrl.most_common(10)) or 'none'}")
    P("")

    P("## 2. File classes (decided by token shape, not filename)")
    P("")
    for k in ('table', 'script/tagged', 'prose', 'empty'):
        fs = sorted(buckets.get(k, []))
        P(f"**{k}** ({len(fs)}): " + ", ".join(f"`{f}`" for f in fs))
        P("")
    P("Tag vocabulary seen in the script/tagged class:")
    tags = collections.Counter()
    for p in paths:
        for m in re.finditer(r'^(text|endtext|pos|help|[a-z]+item)\b',
                             open(p, 'rb').read().decode('cp437', 'replace'), re.M):
            tags[m.group(1)] += 1
    P("")
    P("| tag | count |")
    P("|---|---|")
    for t, c in tags.most_common(12):
        P(f"| {t} | {c} |")
    P("")
    P("The `text`/`endtext`/`pos` triple is a screen-layout DSL (dialog body plus")
    P("pixel position) shared by every UI help/tutorial file; its full vocabulary is")
    P("an open item (OQ-012) because the parser lives in the exe (`helpwin.c`,")
    P("`eventwnd.c`, `winmgr.c` per the module map below).")
    P("")

    text = "\n".join(out) + "\n"
    open(os.path.join(ROOT, 'docs', 're', 'text.md'), 'w').write(text)

    # ---------------- modules doc ----------------
    cnt, first, exe = module_map()
    m = []
    Q = m.append
    Q("# Subsystem map from the shipped binary (P2 spine)")
    Q("")
    Q(f"Evidence: `game/ascend.exe` is **not stripped of module names** — {len(cnt)}")
    Q(f"distinct C/C++ source-file name strings occur, {sum(cnt.values())} times in total.")
    Q("Each is cited by its first raw file offset, so any later claim can be traced.")
    Q("")
    Q("| module | refs | first raw offset | inferred responsibility |")
    Q("|---|---|---|---|")
    ROLE = {
        'ascend.c': 'entry point / init',
        'cfile.c': 'file I/O abstraction',
        'cob.c': '.cob archive reader',
        'cache.c': 'resource cache / shape loading',
        'font.c': 'font (.fnt) loading and text blit',
        'flic.c': 'FLIC player',
        'flicwin.c': 'FLIC window wrapper',
        'cosmos.c': 'galaxy map, star lanes, map generation',
        'ssystem.c': 'star system / planetary surface state',
        'planet.c': 'planet development, population, minerals',
        'planwin.c': 'planet window UI',
        'ship.c': 'ship design, movement, systems',
        'shipgiz.c': 'ship gizmo sprites',
        'shipwin.c': 'ship window UI',
        'race.c': 'race/species attributes',
        'ranceneg.c': 'per-race AI negotiation logic (reads DIPVALUES)',
        'negwnd.c': 'negotiation window UI',
        'research.c': 'technology tree progression',
        'reswin.c': 'research window UI',
        'batmode.c': 'battle mode driver (combat loop)',
        'batcon.c': 'battle control / input during combat',
        'batfx.c': 'battle effects rendering',
        'batfxa.c': 'battle effects audio/animation',
        'corn.c': 'corner/minimap rendering',
        'coswnd.c': 'galaxy map window UI',
        'eventwnd.c': 'event/UI dispatch DSL parser',
        'gwindow.c': 'generic window base class',
        'helpwin.c': 'help windows',
        'loadwin.c': 'load-game window',
        'name.c': 'name generation',
        'psqwin.c': 'planet-square / tile popup window',
        'status.c': 'status display, turn report',
        'winmgr.c': 'window manager, event loop, render primitives',
    }
    for n, c in sorted(cnt.items(), key=lambda kv: -kv[1]):
        Q(f"| `{n}` | {c} | {first[n]:#08x} | {ROLE.get(n, '(unassigned)')} |")
    Q("")
    Q("Unassigned modules are listed as-is; roles above are **[inferred]** from the")
    Q("name plus the extracted data files they obviously correspond to, and each one")
    Q("must be confirmed against the code before a formula cites it (PLAN rule 1).")
    Q("")
    Q("## What this does and does not buy us")
    Q("")
    Q("- It gives the P2 deliverable structure (9 subsystems -> these 34 modules), so")
    Q("  docs/re specs can be named after real compilation units.")
    Q("- It does NOT give function addresses: without an LE loader the linear image")
    Q("  cannot be reconstructed, so no function can be located. See docs/BLOCKED.md")
    Q("  and OQ-008.")
    Q("")
    open(os.path.join(ROOT, 'docs', 're', 'modules.md'), 'w').write("\n".join(m) + "\n")

    if not args.quiet:
        print(text)
    print(f"[text_probe] OK: {len(files)} files, high bytes={sorted(hex(x) for x in hi)}, "
          f"modules={len(cnt)}", file=sys.stderr)
    if len(hi) > 4:
        print("[text_probe] WARN: many high bytes — CP437-only claim no longer safe",
              file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
